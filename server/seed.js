const importData = async () => {
  try {
    await connectDB();

    console.log(`Starting non-destructive safe upsert for ${destinations.length} Sri Lankan destinations...`);

    let insertedCount = 0;
    let updatedCount = 0;

    for (const d of destinations) {
      const existing = await Destination.findOne({ name: d.name });
      if (existing) {
        await Destination.findByIdAndUpdate(existing._id, { $set: d });
        updatedCount++;
      } else {
        await Destination.create(d);
        insertedCount++;
      }
    }

    const totalInDb = await Destination.countDocuments();

    console.log('================================================================');
    console.log('✅ DESTINATION SEEDING COMPLETED SUCCESSFULLY!');
    console.log(`- Inserted new destinations: ${insertedCount}`);
    console.log(`- Updated existing destinations: ${updatedCount}`);
    console.log(`- Total destinations now stored in MongoDB: ${totalInDb}`);
    console.log('================================================================');

    await mongoose.connection.close();
    process.exit(0);
  } catch (error) {
    console.error(`❌ Error importing destinations into MongoDB: ${error.message}`);
    process.exit(1);
  }
};

